// Helper utilities for product operations
const ProductService = {
  getAll: () => DIAMOND_PRODUCTS.map(p => {
    let cond = p.condition;
    if (!cond) {
      if (p.id.includes('15') || p.id.includes('s24') || p.id.includes('watch-6') || p.id.includes('buds-fe') || p.id.includes('mate-60') || p.id.includes('ult-wear') || p.id.includes('linkbuds')) {
        cond = 'like-new';
      } else if (p.id.includes('14') || p.id.includes('watch-se')) {
        cond = 'certified';
      } else {
        cond = 'new';
      }
    }
    return { ...p, condition: cond };
  }),
  getById: function(id) {
    return this.getAll().find(p => p.id === id) || null;
  },
  getByCategory: function(category) {
    const all = this.getAll();
    return (!category || category === 'all') ? all : all.filter(p => p.category === category);
  },
  getByCondition: function(condition) {
    const all = this.getAll();
    return (!condition || condition === 'all') ? all : all.filter(p => p.condition === condition);
  },
  getFeatured: function() {
    return this.getAll().filter(p => p.isFeatured);
  },
  getBestSellers: function() {
    return this.getAll().filter(p => p.isBestSeller);
  },
  getBrands: function() {
    // Explicit prioritized luxury brands order (Anker completely removed)
    const priority = ["Apple", "Samsung", "Xiaomi", "Huawei", "Sony", "Google"];
    const foundBrands = new Set();
    this.getAll().forEach(p => foundBrands.add(p.brand));
    return priority.filter(b => foundBrands.has(b));
  },
  getConditions: () => [
    { id: 'new', labelKey: 'conditionNeverUsed', tagKey: 'conditionTagNeverUsed', badgeKey: 'conditionBadgeA' },
    { id: 'like-new', labelKey: 'conditionLikeNew', tagKey: 'conditionTagLikeNew', badgeKey: 'conditionBadgeB' },
    { id: 'certified', labelKey: 'conditionCertified', tagKey: 'conditionTagCertified', badgeKey: 'conditionBadgeC' }
  ],
  getRelated: function(id, limit = 4) {
    const current = this.getById(id);
    if (!current) return this.getAll().slice(0, limit);
    return this.getAll()
      .filter(p => p.id !== id && (p.category === current.category || p.brand === current.brand))
      .slice(0, limit);
  },
  search: function(query, lang = 'en') {
    if (!query || query.trim() === '') return this.getAll();
    const q = query.toLowerCase().trim();
    return this.getAll().filter(p => {
      const name = (p.name[lang] || p.name.en).toLowerCase();
      const desc = (p.description[lang] || p.description.en).toLowerCase();
      const brand = p.brand.toLowerCase();
      const category = p.category.toLowerCase();
      const condition = p.condition || '';
      return name.includes(q) || desc.includes(q) || brand.includes(q) || category.includes(q) || condition.includes(q);
    });
  }
};
