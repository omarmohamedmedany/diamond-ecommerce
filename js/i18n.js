const I18n = {
  currentLang: localStorage.getItem('diamond_lang') || 'en',

  init() {
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  },

  getLang() {
    return this.currentLang;
  },

  t(key) {
    const langObj = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    return langObj[key] || TRANSLATIONS.en[key] || key;
  },

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'ar') lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('diamond_lang', lang);
    this.applyLanguage(lang);
    
    window.dispatchEvent(new CustomEvent('diamond:languageChanged', { detail: { lang } }));
  },

  toggleLanguage() {
    const newLang = this.currentLang === 'en' ? 'ar' : 'en';
    this.setLanguage(newLang);
  },

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    if (lang === 'ar') {
      document.body.classList.add('rtl-layout');
    } else {
      document.body.classList.remove('rtl-layout');
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) el.placeholder = translation;
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const translation = this.t(key);
      if (translation) el.title = translation;
    });

    const langBtns = document.querySelectorAll('.btn-lang-toggle');
    langBtns.forEach(btn => {
      btn.innerHTML = lang === 'en' 
        ? `<span class="lang-text">العربية</span>`
        : `<span class="lang-text">English</span>`;
    });
  },

  bindEvents() {
    document.addEventListener('click', (e) => {
      const toggleBtn = e.target.closest('.btn-lang-toggle');
      if (toggleBtn) {
        e.preventDefault();
        this.toggleLanguage();
      }
    });
  }
};

document.addEventListener('DOMContentLoaded', () => {
  I18n.init();
});
