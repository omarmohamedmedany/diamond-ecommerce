const I18n = {
  currentLang: localStorage.getItem('diamond_lang') || 'en',

  init() {
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  },

  getLang() {
    return this.currentLang;
  },

  t(key) {
    const langObj = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    return langObj[key] || TRANSLATIONS.en[key] || key;
  },

  getBrandName(brand, lang = this.currentLang) {
    if (!brand) return '';
    if (lang !== 'ar') return brand;
    const map = {
      'apple': 'آبل',
      'samsung': 'سامسونج',
      'xiaomi': 'شاومي',
      'huawei': 'هواوي',
      'sony': 'سوني',
      'google': 'جوجل'
    };
    return map[brand.toLowerCase()] || brand;
  },

  getBadgeName(badge, lang = this.currentLang) {
    if (!badge) return '';
    if (lang !== 'ar') return badge;
    const map = {
      'flagship': 'إصدار رائد',
      'pro': 'برو',
      'popular': 'الأكثر شهرة',
      'new': 'جديد',
      'special offer': 'عرض خاص',
      'limited': 'إصدار محدود',
      'essential': 'أساسي',
      'classic': 'كلاسيك',
      'ultra rugged': 'فائق التحمل',
      'luxury': 'فاخر',
      'diamond care+': 'دايموند كير+'
    };
    return map[badge.toLowerCase()] || badge;
  },

  formatStorage(storage, lang = this.currentLang) {
    if (!storage) return '';
    const size = typeof storage === 'string' ? storage : (storage.size || '');
    if (lang !== 'ar') return size;
    return size.replace(/GB/gi, ' جيجابايت').replace(/TB/gi, ' تيرابايت');
  },

  formatPrice(amount, lang = this.currentLang) {
    if (amount === undefined || amount === null || isNaN(amount)) return '';
    const num = Math.round(Number(amount));
    if (lang === 'ar') {
      const formatted = num.toLocaleString('en-US');
      const arabicDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
      const arabicNum = formatted.replace(/\d/g, d => arabicDigits[d]).replace(/,/g, '،');
      return `${arabicNum} ر.ق`;
    } else {
      return `${num.toLocaleString('en-US')} QR`;
    }
  },

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'ar') lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('diamond_lang', lang);
    this.applyLanguage(lang);
    
    window.dispatchEvent(new CustomEvent('diamond:languageChanged', { detail: { lang } }));
  },

  toggleLanguage() {
    const newLang = this.currentLang === 'en' ? 'ar' : 'en';
    this.setLanguage(newLang);
  },

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    if (lang === 'ar') {
      document.body.classList.add('rtl-layout');
    } else {
      document.body.classList.remove('rtl-layout');
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) el.placeholder = translation;
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const translation = this.t(key);
      if (translation) el.title = translation;
    });

    const langBtns = document.querySelectorAll('.btn-lang-toggle');
    langBtns.forEach(btn => {
      btn.innerHTML = lang === 'en' 
        ? `<span class="lang-text">العربية</span>`
        : `<span class="lang-text">English</span>`;
    });

    const priceDisplay = document.getElementById('price-range-val');
    const priceSlider = document.getElementById('price-range-slider');
    if (priceDisplay && priceSlider) {
      const currentVal = parseInt(priceSlider.value, 10) || 6000;
      priceDisplay.textContent = this.formatPrice(currentVal, lang);
    }
  },

  bindEvents() {
    document.addEventListener('click', (e) => {
      const toggleBtn = e.target.closest('.btn-lang-toggle');
      if (toggleBtn) {
        e.preventDefault();
        this.toggleLanguage();
      }
    });
  }
};

window.I18n = I18n;

document.addEventListener('DOMContentLoaded', () => {
  I18n.init();
});
